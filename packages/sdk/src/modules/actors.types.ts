/**
 * Maps actor names to their message types and method types.
 *
 * Extend this interface when you want typed actor messages and method calls without generating
 * types with the CLI:
 * - `toServer`: Defines incoming messages that a client sends to the actor.
 * - `toClient`: Defines outgoing messages that the actor sends to connected clients.
 * - `methods`: Defines the actor's methods that you can call on a session. Each entry's argument
 *   and return types become the types of the matching [method call](#session-methods).
 *
 * To generate types from deployed actors, use the
 * [`types generate`](/developers/references/cli/commands/types-generate) CLI command.
 * 
 * To learn how incoming and outgoing messages work, see
 * [message types](/developers/backend/resources/actors/overview#message-types).
 *
 * @example
 * ```typescript
 * // Type messages for an actor
 * declare module "@base44/sdk" {
 *   interface ActorRegistry {
 *     chatRoom: {
 *       toClient: { type: "joined" | "left" | "message"; userId?: string; from?: string; text?: string };
 *       toServer: { type: "message"; text: string };
 *       methods: { kick: (args: { userId: string }) => { kicked: boolean } };
 *     };
 *   }
 * }
 * ```
 */
export interface ActorRegistry {}

/**
 * Lists actor names when your project includes types generated by the CLI
 * with [`types generate`](/developers/references/cli/commands/types-generate).
 *
 * The generated names provide autocomplete for deployed actors. To define
 * incoming and outgoing message types manually, augment {@linkcode ActorRegistry}.
 */
export interface ActorNameRegistry {}

type AllActorNames = keyof ActorRegistry | keyof ActorNameRegistry;

type ToClientFor<N extends string> = N extends keyof ActorRegistry
  ? ActorRegistry[N] extends { toClient: infer I }
    ? I
    : unknown
  : unknown;

type ToServerFor<N extends string> = N extends keyof ActorRegistry
  ? ActorRegistry[N] extends { toServer: infer O }
    ? O
    : unknown
  : unknown;

type ActorMethodCall<F> = F extends (args: infer A, ...rest: never[]) => infer R
  ? undefined extends A
    ? (args?: A) => Promise<Awaited<R>>
    : (args: A) => Promise<Awaited<R>>
  : never;

type UntypedActorMethods = Record<string, (args?: unknown) => Promise<unknown>>;

/**
 * An actor's callable methods, as seen by a caller: each runs the actor's method of the same
 * name with one JSON argument and resolves to its return value. Typed from the actor's `methods`
 * in {@linkcode ActorRegistry}; any name otherwise.
 */
export type ActorMethods<N extends string> = N extends keyof ActorRegistry
  ? ActorRegistry[N] extends { methods: infer M }
    ? { [K in keyof M]: ActorMethodCall<M[K]> }
    : UntypedActorMethods
  : UntypedActorMethods;

/**
 * Configures the connection that {@linkcode ActorConnectable.connect | connect()} opens.
 */
export interface ActorConnectOptions {
  /**
   * Connection ID that the actor receives as `conn.id`.
   *
   * To let the actor recognize a client when it reconnects, use a stable
   * value, such as an ID stored per browser tab. If you omit this property, the
   * SDK generates a new connection ID.
   */
  id?: string;
}

/**
 * Represents a listener for messages from the actor, registered with
 * {@linkcode Connection.subscribe | subscribe()}.
 */
export interface ActorSubscription {
  /**
   * Removes this listener. Other listeners and the socket stay open.
   *
   * @example
   * ```typescript
   * // Remove a listener
   * sub.unsubscribe();
   * ```
   */
  unsubscribe(): void;
}

/**
 * Represents a client's [WebSocket](https://developer.mozilla.org/en-US/docs/Web/API/WebSockets_API) connection to an actor session, returned after calling
 * [`connect()`](#connect). The WebSocket queues messages you send before it opens.
 * 
 * Learn more about
 * [connections](/developers/backend/resources/actors/reference#connections).
 */
export interface Connection<N extends string = string> {
  /** Connection ID that the actor receives as `conn.id`. */
  readonly id: string;

  /**
   * Registers a listener for messages from the actor.
   *
   * You can register multiple listeners on the same connection.
   *
   * @param callback - Callback that runs for each message the actor sends to this connection.
   * @returns A subscription handle. Call `unsubscribe()` on it to remove this listener without closing the socket.
   *
   * @example
   * ```typescript
   * // Listen for messages from the actor
   * const sub = conn.subscribe((msg) => {
   *   console.log(msg);
   * });
   *
   * // Stop listening without closing the socket.
   * sub.unsubscribe();
   * ```
   */
  subscribe(callback: (data: ToClientFor<N>) => void): ActorSubscription;

  /**
   * Sends a message to the actor.
   *
   * The WebSocket queues messages until it opens. When you call {@linkcode Connection.close | close()},
   * the WebSocket drops any messages you send afterward.
   *
   * @param data - Message to send to the actor. The type comes from {@linkcode ActorRegistry} when you register the actor there.
   *
   * @example
   * ```typescript
   * // Send a message to the actor
   * conn.send({ type: "message", text: "Hello" });
   * ```
   */
  send(data: ToServerFor<N>): void;

  /**
   * Closes the connection and removes all listeners.
   *
   * You can call this method more than once. A connection also closes itself
   * when it fails permanently.
   *
   * @example
   * ```typescript
   * // Close the connection
   * conn.close();
   * ```
   */
  close(): void;
}

/**
 * Represents a reference to an actor session, identified by actor name and session ID.
 *
 * Call {@linkcode ActorConnectable.connect | connect()} to open a WebSocket and get a
 * [connection](/developers/backend/resources/actors/overview#connections) that sends and receives
 * messages.
 *
 * You can also call a method you wrote in the actor by name, such as a `kick()` method that
 * removes a user from a chat room. The method runs on the session even when no client is
 * connected, and the call resolves to its return value.
 *
 * A method call takes one argument, which can be any JSON value. To pass several values, wrap
 * them in an object. The actor receives the caller's identity, which is the current user, or an
 * anonymous visitor when the client uses anonymous authentication. If the actor refuses the call,
 * the promise rejects with a
 * [`Base44Error`](/developers/references/sdk/getting-started/work-with-sdk#error-handling).
 *
 * To type a method's argument and return value, add the actor's `methods` to
 * {@linkcode ActorRegistry}. To learn which methods an actor accepts, how arguments are
 * encoded, and the size and rate limits, see
 * [callable methods](/developers/backend/resources/actors/reference#callable-methods).
 *
 * @example
 * ```typescript
 * // Connect to a session and listen for messages
 * const conn = base44.actors.chatRoom("session-1").connect();
 * conn.subscribe((msg) => {
 *   console.log(msg);
 * });
 * ```
 *
 * @example
 * ```typescript
 * // Call a method on a session
 * const { kicked } = await base44.actors.chatRoom("session-1").kick({ userId: "user-123" });
 * ```
 */
export interface ActorConnectable<N extends string = string> {
  /**
   * Creates or returns the connection for this session.
   *
   * Calling `connect()` again on the same session reference returns the same
   * connection until it closes.
   *
   * For a sample flow, see
   * [connect a client to a session](/developers/backend/resources/actors/sample-flows#connect-a-client-to-a-session).
   *
   * @param options - Optional connection settings, such as a stable connection ID.
   * @returns The connection for this actor session.
   *
   * @example
   * ```typescript
   * // Connect to a session
   * const conn = base44.actors.chatRoom("session-1").connect({ id: "tab-1" });
   * ```
   */
  connect(options?: ActorConnectOptions): Connection<N>;

}

export type ActorRef<N extends string = string> = ActorConnectable<N> & ActorMethods<N>;

/**
 * Represents a reference to an actor session for server code running with the
 * [service role](/developers/references/sdk/getting-started/client#service-role).
 * Server code can't hold a connection, so it can only call the actor's methods. The actor
 * receives the `service` identity.
 *
 * @example
 * ```typescript
 * // Remove a user from a chat room from server code
 * await base44.asServiceRole.actors.chatRoom("session-1").kick({ userId: "user-123" });
 * ```
 */
export type ServiceRoleActorRef<N extends string = string> = ActorMethods<N>;

/**
 * Actors module available with the service role: selects a session whose methods to call.
 */
export type ServiceRoleActorsModule = {
  [K in AllActorNames]: (instanceId: string) => ServiceRoleActorRef<string & K>;
} & Record<string, (instanceId: string) => ServiceRoleActorRef>;

/**
 * Selects a session for a named actor.
 *
 * TypeScript infers message types and method types when you register the actor in
 * {@linkcode ActorRegistry}. {@linkcode ActorNameRegistry}
 * provides autocomplete for actor names only.
 */
export interface ActorClient<N extends string = string> {
  /**
   * Gets a reference to an actor session.
   *
   * Clients that specify the same actor name and session ID join the same session.
   *
   * @param instanceId - Session ID that identifies which session to connect to.
   * @returns A [reference to the actor session](#session-methods).
   *
   * @example
   * ```typescript
   * // Select a session
   * const session = base44.actors.chatRoom("session-1");
   * ```
   */
  (instanceId: string): ActorRef<N>;
}

/**
 * Actors module for interacting with [actors](/developers/backend/resources/actors/overview) from your app.
 *
 * An actor is a long-running backend process that multiple clients connect to simultaneously. A session
 * is a running instance of an actor, identified by the actor name and a session ID. Each
 * session manages its own state, storage, and client connections independently.
 *
 * The actors module provides the functionality to:  
 *
 * - Manage connections: {@link ActorConnectable.connect | Open} and {@link Connection.close | close} a WebSocket connection to a session.
 * - Exchange messages: {@link Connection.send | Send} and {@link Connection.subscribe | listen} for messages to and from an actor.
 * - Manage subscriptions: {@link Connection.subscribe | Subscribe} and {@link ActorSubscription.unsubscribe | unsubscribe} from actor messages without closing the connection.
 * - Call methods: {@link ActorConnectable | Run} a method you wrote in the actor on a session, without connecting to it.
 *
 * For a sample flow, see
 * [connect a client to a session](/developers/backend/resources/actors/sample-flows#connect-a-client-to-a-session).
 *
 * ## Authentication modes
 *
 * This module is available to use with a client in all authentication modes:
 *
 * - **Anonymous or user authentication** (`base44.actors`): Opens connections to sessions,
 *   exchanges messages, and calls an actor's methods.
 * - **[Service role authentication](/developers/references/sdk/getting-started/client#service-role)**
 *   (`base44.asServiceRole.actors`): Calls an actor's methods. Server code can't hold a
 *   connection, so it can't connect to a session.
 *
 * The actor receives each client's [identity](/developers/backend/resources/actors/reference#connections)
 * when the client connects or calls a method. A client that hasn't logged in is anonymous, a client that
 * has [logged in](/developers/references/sdk/docs/interfaces/auth) is authenticated, and server
 * code calling with the service role is `service`.
 */
export type ActorsModule = {
  [K in AllActorNames]: K extends keyof ActorRegistry
    ? ActorClient<string & K>
    : ActorClient;
} & Record<string, ActorClient>;
