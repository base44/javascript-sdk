// Generates src/server/modules/webhooks.events.generated.ts from the published event JSON Schemas.
//
//   npm run generate:webhooks                        # fetch https://base44.com/webhooks/schemas
//   npm run generate:webhooks -- --from <schemas dir> # local apper checkout
//   npm run generate:webhooks -- --openapi <url or file>
//
// The outbound webhooks OpenAPI (WEBHOOKS_OPENAPI_URL, by default production's) says which events are
// deprecated; their types get a `@deprecated` tag, and verifyEvent() warns once when one arrives.
// `--from` changes only where the schemas come from: to try a local deprecation, pass `--openapi` too.
// The notices are kept in scripts/webhook-deprecations.json, so an event that leaves the spec keeps its own.
//
// The event list is scripts/webhook-event-types.json: add a type there and rerun to pick up a new event.
//
// An additive change to an event (a new optional field, a new enum value) keeps its type and publishes
// the next schema revision: revision 1 at <type>.json, revision N at <type>/<N>.json. Published files
// never change and revisions are numbered without gaps, so each type is generated from the highest one
// found by trying <type>/2.json, 3.json, … until one is missing.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import { deprecations } from "./webhook-deprecations.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, "../src/server/modules/webhooks.events.generated.ts");
const fromIndex = process.argv.indexOf("--from");
const source = fromIndex === -1 ? "https://base44.com/webhooks/schemas" : process.argv[fromIndex + 1];
if (!source) throw new Error("--from needs a value");

const openapiIndex = process.argv.indexOf("--openapi");
const openapiSource =
  openapiIndex === -1
    ? (process.env.WEBHOOKS_OPENAPI_URL ?? "https://app.base44.com/api/v1/outbound-webhooks/openapi.json")
    : process.argv[openapiIndex + 1];
if (!openapiSource) throw new Error("--openapi needs a value");

async function readOpenapi() {
  if (!/^https?:/.test(openapiSource)) return JSON.parse(await readFile(openapiSource, "utf8"));
  const response = await fetch(openapiSource);
  if (!response.ok) throw new Error(`GET ${openapiSource} returned ${response.status}`);
  return response.json();
}

const notesFile = path.join(here, "webhook-deprecations.json");
const deprecated = deprecations(await readOpenapi(), JSON.parse(await readFile(notesFile, "utf8")));
const types = JSON.parse(await readFile(path.join(here, "webhook-event-types.json"), "utf8"));

// The schema at `file` under the source, or null when it isn't published.
async function read(file) {
  if (/^https?:/.test(source)) {
    const response = await fetch(`${source}/${file}`);
    if (response.status === 404) return null;
    if (!response.ok) throw new Error(`${file}: HTTP ${response.status}`);
    return response.json();
  }
  try {
    return JSON.parse(await readFile(path.join(source, file), "utf8"));
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

// The type's latest schema revision.
async function load(type) {
  let schema = await read(`${type}.json`);
  if (!schema) throw new Error(`${type}: no schema at ${source}/${type}.json`);
  for (let revision = 2; ; revision++) {
    const next = await read(`${type}/${revision}.json`);
    if (!next) return schema;
    schema = next;
  }
}

// A new enum value is additive, so it arrives in a later revision of the same type, and a receiver
// generated from an earlier one can get it. Every string enum is typed open: its known values still
// autocomplete and narrow, and `(string & {})` admits the rest.
function openEnums(node) {
  if (Array.isArray(node)) return node.map(openEnums);
  if (!node || typeof node !== "object") return node;
  const copy = Object.fromEntries(Object.entries(node).map(([key, value]) => [key, openEnums(value)]));
  if (Array.isArray(node.enum) && node.enum.every(value => typeof value === "string")) {
    copy.tsType = [...node.enum.map(value => JSON.stringify(value)), "(string & {})"].join(" | ");
  }
  return copy;
}

// "app.created.v1" -> "AppCreatedV1Data"
const dataName = type => type.split(/[._]/).map(part => part[0].toUpperCase() + part.slice(1)).join("") + "Data";

let body = `// Generated by scripts/generate-webhook-types.mjs from the latest schema revision of each event
// published at https://base44.com/webhooks/schemas. Do not edit by hand; run \`npm run generate:webhooks\`.

`;
const docs = {};
for (const type of types) {
  const { $schema, $id, examples, ...schema } = await load(type);
  docs[type] = schema.description.replace(/^The `data` object of `[^`]+`\. /, "").replace(/\*\//g, "* /");
  if (deprecated[type]) schema.description += `\n\n@deprecated ${deprecated[type]}`;
  // Later revisions drop `additionalProperties: false` so receivers ignore fields added after them.
  // A TypeScript interface accepts extra fields anyway, so leave out the index signature that an open
  // schema would get and keep property typos a compile error.
  body += await compile({ ...openEnums(schema), title: dataName(type) }, dataName(type), {
    bannerComment: "",
    additionalProperties: false,
    format: true,
    strictIndexSignatures: true,
  });
}
body += `/** Every event type Base44 sends, mapped to the shape of its \`data\` object. */\nexport interface WebhookEventMap {\n`;
for (const type of types) {
  const summary = docs[type].split("\n")[0];
  const doc = deprecated[type] ? `/**\n   * ${summary}\n   *\n   * @deprecated ${deprecated[type]}\n   */` : `/** ${summary} */`;
  body += `  ${doc}\n  "${type}": ${dataName(type)};\n`;
}
body += "}\n";
body += `\n/** Every event type in {@link WebhookEventMap}, so events from a newer Base44 can be told apart at runtime. @internal */\nexport const WEBHOOK_EVENT_TYPES = ${JSON.stringify(types)} as const;\n`;
body += `\n/** The deprecation notice of each deprecated event type, for verifyEvent()'s warning. @internal */\nexport const WEBHOOK_DEPRECATIONS: Partial<Record<string, string>> = ${JSON.stringify(deprecated)};\n`;

await writeFile(out, body);
await writeFile(notesFile, JSON.stringify(deprecated, null, 2) + "\n");
console.log(`Wrote ${types.length} event types to ${path.relative(process.cwd(), out)}`);
