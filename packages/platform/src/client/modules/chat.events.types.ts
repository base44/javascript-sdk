import type { Message, QueueState, ServerEventMap, Snapshot } from "./chat.events.generated.js";

/**
 * Maps each live event name to the type of its `data` payload.
 *
 * Generated from the service's AsyncAPI document, so it covers every app event the service sends.
 * The client handles the session events `app.snapshot`, `session.ended` and `room.*` itself, and
 * reports them through `onSnapshot` and `onError` instead.
 */
export type PlatformEventMap = {
  [K in keyof ServerEventMap as K extends "app.snapshot" | "session.ended" | `room.${string}` ? never : K]: ServerEventMap[K];
};

/** An event the service sends for a subscribed app, named by its `type`. */
export interface AppEvent<K extends keyof PlatformEventMap> {
  /** Event name. Narrows the type of `data`. */
  type: K;
  /** ID of the app the event belongs to. */
  appId: string;
  /** Event payload. */
  data: PlatformEventMap[K];
}

/** An event this version of the SDK doesn't know. */
export interface UnknownEvent {
  /** Always `"unknown"`. */
  type: "unknown";
  /** The event's name on the socket. */
  name: string;
  /** ID of the app the event belongs to. */
  appId: string;
  /** Event payload, not checked by the SDK. */
  data: Record<string, unknown>;
}

/**
 * A live event for a subscribed app.
 *
 * Check `type` to narrow `data` to that event's payload. The `data` of an event holds only the
 * fields that changed. Keep your value for any field the event leaves out, and clear a field the
 * event sets to `null`.
 * [Socket messages](/developers/references/apps-api/sections/socket-messages) lists every event
 * and its payload.
 *
 * An event added to the service after this version of the SDK arrives with `type: "unknown"`, its
 * event name in `name`, and an unchecked `data`, so check a field before using it. After you
 * upgrade, the event arrives under its own `type`.
 *
 * @example
 * ```typescript
 * // Narrow an event by type
 * function onEvent(event: PlatformEvent) {
 *   if (event.type === "message.updated") {
 *     const { message } = event.data;
 *     console.log(`Message ${message.id} changed`);
 *   }
 *   // A hypothetical event this version of the SDK doesn't know yet
 *   if (event.type === "unknown" && event.name === "app.renamed" && typeof event.data.name === "string") {
 *     console.log(`App renamed to ${event.data.name}`);
 *   }
 * }
 * ```
 */
export type PlatformEvent =
  // Generated by scripts/gen-events.mjs, begin
  | AppEvent<"message.updated">
  | AppEvent<"message.removed">
  | AppEvent<"app.status_changed">
  | AppEvent<"preview.reload_requested">
  | AppEvent<"preview.navigation_requested">
  | AppEvent<"queue.updated">
  | AppEvent<"task.progressed">
  | AppEvent<"image.resolved">
  | AppEvent<"conversation.changed">
  | AppEvent<"files.changed">
  | AppEvent<"branch.deleted">
  | AppEvent<"repository.changed">
  | AppEvent<"pull_request.changed">
  // Generated by scripts/gen-events.mjs, end
  | UnknownEvent;

/**
 * An app's current state.
 *
 * The snapshot arrives when you subscribe, after every reconnect, and after the main conversation
 * is rewritten. Replace everything you hold for the app with the snapshot. A snapshot holds only
 * the last 50 messages.
 */
export interface PlatformSnapshot extends Omit<Snapshot, "queue"> {
  /** Identifies the app the snapshot is for, in the form `/apps/{app_id}`. */
  room: string;
  /** The main branch's prompt queue. Missing when the server sends none. */
  queue?: QueueState;
}

/**
 * One tool call in a message's `tool_calls`. Checking `name` narrows it to that tool's call and
 * `OtherToolCall`, which covers tools the SDK doesn't know, so check a field with `in` before using it.
 */
export type ToolCall = NonNullable<Message["tool_calls"]>[number];

/** Why a safety guard parked a tool call for approval. Check `guard` to narrow it. */
export type GuardApproval = NonNullable<ToolCall["approval"]>;
